import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createSessionServer } from './sessions.mjs';

test('checkpoint branches restore independent dialogue, settings, and memory after restart', async () => {
  const folder=await mkdtemp(join(tmpdir(),'d10-branch-api-')); let server;
  const start=async()=>{server=createSessionServer(join(folder,'test.sqlite'));await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));return `http://127.0.0.1:${server.address().port}/api/sessions`;};
  const stop=()=>new Promise(resolve=>server.close(resolve));
  const post=(url,body={})=>fetch(url,{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(body)});
  const patch=(url,body)=>fetch(url,{method:'PATCH',headers:{'Content-Type':'application/json'},body:JSON.stringify(body)});
  const put=(url,body)=>fetch(url,{method:'PUT',headers:{'Content-Type':'application/json'},body:JSON.stringify(body)});
  let base=await start();
  const root=await (await post(base)).json();
  const memory=await (await post(`${base}/${root.id}/memory-session`)).json();
  await patch(`${base}/${root.id}`,{memorySelected:1});
  await patch(`${base}/${memory.id}`,{recentMessages:7});
  const event=(sessionId,id,text)=>({id:`event-${id}`,sessionId,type:'message',payload:{id,conversationId:sessionId,runId:`run-${id}`,createdAt:1,role:'user',type:'text',text}});
  assert.equal((await post(`${base}/${memory.id}/events`,event(memory.id,'shared','Общая встреча'))).status,201);
  assert.equal((await put(`${base}/${memory.id}/memory`,{revision:0,entries:[{id:'meeting',key:'Встреча',value:'Место: парк'}]})).status,200);
  const cpResponse=await post(`${base}/${root.id}/checkpoints`,{name:'Общее начало'}); assert.equal(cpResponse.status,201); const cp=await cpResponse.json();
  const make=async name=>{const r=await post(`${base}/${root.id}/branches`,{checkpointId:cp.id,name});assert.equal(r.status,201);return r.json();};
  const left=await make('Утро'), right=await make('День');
  const leftMemory=await (await post(`${base}/${left.id}/memory-session`)).json();
  const rightMemory=await (await post(`${base}/${right.id}/memory-session`)).json();
  assert.equal(left.memorySelected,1); assert.equal(leftMemory.recentMessages,7);
  assert.equal((await post(`${base}/${leftMemory.id}/events`,event(leftMemory.id,'left','12:00'))).status,201);
  assert.equal((await post(`${base}/${rightMemory.id}/events`,event(rightMemory.id,'right','15:00'))).status,201);
  await put(`${base}/${leftMemory.id}/memory`,{revision:1,entries:[{id:'meeting',key:'Встреча',value:'12:00'}]});
  await put(`${base}/${rightMemory.id}/memory`,{revision:1,entries:[{id:'meeting',key:'Встреча',value:'15:00'}]});
  await stop(); base=await start();
  assert.deepEqual((await (await fetch(`${base}/${leftMemory.id}/events`)).json()).map(e=>e.payload.text),['Общая встреча','12:00']);
  assert.deepEqual((await (await fetch(`${base}/${rightMemory.id}/events`)).json()).map(e=>e.payload.text),['Общая встреча','15:00']);
  assert.equal((await (await fetch(`${base}/${leftMemory.id}/memory`)).json()).entries[0].value,'12:00');
  assert.equal((await (await fetch(`${base}/${rightMemory.id}/memory`)).json()).entries[0].value,'15:00');
  assert.equal((await (await fetch(`${base}/${memory.id}/memory`)).json()).entries[0].value,'Место: парк');
  await stop();
});
